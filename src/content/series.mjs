/** FAQ, scoring, and the two signature notes. One page each, in every language the site already has. */

const section = (h2, paragraphs) => ({ h2, paragraphs });
const faq = (q, a) => ({ q, a });
const link = (href, label) => ({ href, label });

function page(homeHref, crumb, crumbHere, title, description, h1, lede, sections, faqsTitle, faqs, more) {
  return { title, description, homeHref, crumb, crumbHere, h1, lede, sections, faqsTitle, faqs, more };
}

function pack(code, t) {
  const p = code === "en" ? "" : `/${code}`;
  const home = p || "/";
  const signature = `${p}/tools/signature`;
  const indexed = code === "en" || code === "zh";
  const sizeHref = indexed ? `${p}/guides/signature-size` : `${p}/tools/signature/size`;
  const bodyHref = indexed ? `${p}/guides/signature-writing` : `${p}/tools/signature/body`;
  return {
    navFaq: t.navFaq,
    navAbout: t.navAbout,
    notesTitle: t.notesTitle,
    notes: [link(sizeHref, t.sizeNav), link(bodyHref, t.bodyNav)],
    faq: page(
      home,
      t.crumb,
      t.navFaq,
      t.faqTitle,
      t.faqDescription,
      t.faqH1,
      t.faqLede,
      t.faqSections || [],
      t.faqsTitle,
      t.faqItems,
      [link(`${p}/science`, t.science), link(`${p}/about`, t.navAbout), link(signature, t.signature), ...(t.faqMore || [])],
    ),
    about: page(
      home,
      t.crumb,
      t.navAbout,
      t.aboutTitle,
      t.aboutDescription,
      t.aboutH1,
      t.aboutLede,
      [section(t.pickH, t.pickP), section(t.scoreH, t.scoreP), ...(t.aboutExtraSections || [])],
      t.faqsTitle,
      t.aboutItems,
      [link(`${p}/science`, t.science), link(`${p}/faq`, t.navFaq), ...(t.aboutMore || [])],
    ),
    size: page(
      signature,
      t.signature,
      t.sizeNav,
      t.sizeTitle,
      t.sizeDescription,
      t.sizeH1,
      t.sizeLede,
      [section(t.sizeBoxH, t.sizeBoxP), section(t.sizeLimitH, t.sizeLimitP)],
      t.faqsTitle,
      t.sizeItems,
      [link(signature, t.backTool), link(bodyHref, t.bodyNav)],
    ),
    body: page(
      signature,
      t.signature,
      t.bodyNav,
      t.bodyTitle,
      t.bodyDescription,
      t.bodyH1,
      t.bodyLede,
      [section(t.bodyDiffH, t.bodyDiffP), section(t.bodyUseH, t.bodyUseP)],
      t.faqsTitle,
      t.bodyItems,
      [link(signature, t.backTool), link(sizeHref, t.sizeNav), link(home, t.toTest)],
    ),
  };
}

